RUBRIC = """You are grading two scene graphs produced by two different computer-vision \
systems for the SAME photograph. The numbered boxes drawn on the image identify the \
objects; both graphs refer to those same numbers.

Judge each graph AS A WHOLE, not relation by relation. What matters:

1. TRUTH — are the stated relationships actually true of this image? A specific claim \
that is wrong is worse than a generic claim that is right.
2. COVERAGE — a graph that correctly describes more of what is going on is more useful \
than a cautious one that states only the obvious. Reward the fuller account of the \
scene, but only where the extra relationships are true and add something: padding with \
wrong, repeated or trivial claims makes a graph worse, not better.
3. COHERENCE — do the relationships together describe one consistent scene? Penalise \
contradictions (X on Y and Y on X), impossible combinations, and repetition that says \
the same thing many times.
4. SALIENCE — does the graph capture the interactions that matter in this photo, or \
does it spend itself on trivial background facts?
5. USEFULNESS — if someone had only this graph and not the photo, which one would let \
them answer more questions about what is happening?

The two graphs may contain different numbers of relationships. Do not prefer the longer \
list by default — prefer the one that tells you more that is TRUE. \
Ignore differences in wording style; judge what is claimed, not how fluently. \
The order in which the two graphs are shown carries NO information — a graph is not \
better for being presented first.

First write two or three sentences of analysis: name a specific claim in each graph that \
is right or wrong, and say which graph describes more of the scene truthfully. Then, on \
the last line, give your verdict as STRICT JSON and nothing else:
{"winner": "A" | "B" | "tie", "reason": "<one sentence>"}"""


def load_npz(path):
    z = np.load(path, allow_pickle=False)
    d = {k: z[k] for k in z.files}
    d["_meta"] = m = json.loads(str(d["meta"][0]))
    # Records written before `label_base` was stamped: OvSGTR's postprocessor is
    # 1-based (index 0 = __background__). Backfill rather than rewrite the.npz.
    if "label_base" not in m:
        m["label_base"] = 1 if m.get("model") == "OvSGTR" else 0
    return d


def obj_labels(d, i):
    """Object labels for record row i, normalised to 0-based pack category indices.

    `label_base` is 1 for producers whose category space reserves index 0 for
    `__background__` (OvSGTR's postprocessor does: run_ovsgtr_pack.py writes
    `cat_ids + 1`). Reading those as 0-based silently shifts EVERY object name by one
    category — `person` renders as `bicycle` — which is invisible in any metric that
    matches on box index, and catastrophic in anything that shows names to a judge."""
    ba, bb = int(d["box_ptr"][i]), int(d["box_ptr"][i + 1])
    return d["labels"][ba:bb].astype(np.int64) - int(d["_meta"].get("label_base", 0))


def triplets(d, i, max_rel, rel_frac, cat_names, labels=None):
    """The graph this model would actually deploy for record row i.

    Each pair contributes its argmax predicate; pairs are ranked by score and kept while
    `score >= rel_frac * best_score_for_this_image`, capped at `max_rel`. The rule is
    deliberately RELATIVE and per-image: the two models' scores sit on different scales
    (OvSGTR's top pair scores ~0.14 median, ours are sigmoid-fused), so an absolute
    threshold would rank calibration rather than content. A relative one lets each
    model's own confidence spread decide how much it is willing to say — which is the
    property we want to measure, since a model that correctly says more is a better one.

    Column 0 is background for OvSGTR (bg_column=0) and absent for ours (-1).

    `labels` overrides the record's own object labels. In a side-by-side comparison the
    two graphs address the SAME numbered boxes, so they must be named from one shared
    source — otherwise a naming discrepancy in one record reads to the judge as that
    model asserting nonsense, and the comparison measures the harness."""
    a, b = int(d["pair_ptr"][i]), int(d["pair_ptr"][i + 1])
    if b <= a:
        return []
    preds = [str(x) for x in d["predicates"]]
    pairs = d["pairs"][a:b]
    labels = obj_labels(d, i) if labels is None else labels
    sc = d["rel_scores"][a:b].astype(np.float32)
    if d["_meta"].get("emit") == "topk":
        # compact form: already one predicate per pair, columns = (pred_id, score)
        arg, best = sc[:, 0].astype(np.int64), sc[:, 1]
    else:
        bg = int(d["_meta"].get("bg_column", -1))
        if bg >= 0:
            sc = np.delete(sc, bg, axis=1)
        best, arg = sc.max(1), sc.argmax(1)
    order = np.argsort(-best)[:max_rel]
    if len(order):
        order = order[best[order] >= rel_frac * best[order[0]]]
    out, seen = [], set()
    for j in order:
        s, o = int(pairs[j][0]), int(pairs[j][1])
        if s >= len(labels) or o >= len(labels):
            continue
        sn = cat_names[labels[s]] if 0 <= labels[s] < len(cat_names) else "object"
        on = cat_names[labels[o]] if 0 <= labels[o] < len(cat_names) else "object"
        t = (f"{sn}#{s}", preds[int(arg[j])], f"{on}#{o}")
        if t in seen:            # exact duplicates are noise, not coverage
            continue
        seen.add(t)
        out.append(t)
    return out


def scramble(tris, rng, min_changed=0.5):
    """Degenerate control: keep the object pairs, permute the predicates across them.
    Preserves length, vocabulary and object names, so a judge that prefers the intact
    graph is responding to relational content and nothing else.

    Returns None when scrambling would not actually corrupt the graph. A graph that is
    four copies of `on` permutes into itself, and scoring the judge on such a pair would
    charge it for a task with no right answer — that is our degenerate case, not its
    failure. Only graphs where at least `min_changed` of the slots really move are used."""
    if len(tris) < 3 or len({t[1] for t in tris}) < 3:
        return None
    ps = [t[1] for t in tris]
    best = None
    for _ in range(50):
        q = ps[:]
        rng.shuffle(q)
        ch = sum(x != y for x, y in zip(ps, q)) / len(ps)
        if best is None or ch > best[0]:
            best = (ch, q)
        if ch >= min_changed:
            break
    if best[0] < min_changed:
        return None
    return [(s, best[1][i], o) for i, (s, _, o) in enumerate(tris)]


def pad(tris, rng, n_extra=4):
    """Length-bias control: the SAME graph plus `n_extra` fabricated relations.

    The additions reuse the graph's own objects and its own predicate strings, on object
    pairs the model did not assert, so the padded graph is strictly longer, strictly
    less true, and identical in vocabulary and style. Since we ask the judge to reward
    coverage, we have to know what it does when coverage is fake: a judge that prefers
    this is counting lines, not facts."""
    if len(tris) < 2:
        return tris
    ents = sorted({t[0] for t in tris} | {t[2] for t in tris})
    ps = sorted({t[1] for t in tris})
    if len(ents) < 2:
        return tris
    have = {(s, o) for s, _, o in tris}
    cand = [(s, o) for s in ents for o in ents if s != o and (s, o) not in have]
    if not cand:
        return tris
    rng.shuffle(cand)
    extra = [(s, ps[rng.randrange(len(ps))], o) for s, o in cand[:n_extra]]
    out = tris + extra
    rng.shuffle(out)          # don't leave the fabrications in a block at the end
    return out


def render(img_path, boxes, labels, cat_names, max_side=1024):
    im = Image.open(img_path).convert("RGB")
    W, H = im.size
    sc = min(1.0, max_side / max(W, H))
    if sc < 1.0:
        im = im.resize((int(W * sc), int(H * sc)), Image.LANCZOS)
    dr = ImageDraw.Draw(im)
    try:
        font = ImageFont.truetype("DejaVuSans-Bold.ttf", 15)
    except Exception:
        font = ImageFont.load_default()
    for i, (bx, lb) in enumerate(zip(boxes, labels)):
        x0, y0, x1, y1 = [v * sc for v in bx]
        dr.rectangle([x0, y0, x1, y1], outline=(255, 210, 0), width=3)
        tag = f"{i}"
        tw = dr.textlength(tag, font=font)
        dr.rectangle([x0, y0, x0 + tw + 8, y0 + 20], fill=(255, 210, 0))
        dr.text((x0 + 4, y0 + 2), tag, fill=(0, 0, 0), font=font)
    return im


def fmt(tris):
    return "\n".join(f"- {s} — {p} → {o}" for s, p, o in tris) or "- (no relations)"


def parse(txt):
    """Take the LAST JSON object: the verdict follows the chain-of-thought analysis, and
    the analysis itself may quote braces."""
    ms = re.findall(r'\{[^{}]*\}', txt, re.S)
    for m in reversed(ms):
        try:
            j = json.loads(m)
        except Exception:
            continue
        w = str(j.get("winner", "")).strip().upper()
        if w in ("A", "B", "TIE"):
            return w, str(j.get("reason", ""))[:300]
    return None, ""


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--a", required=True); p.add_argument("--a_name", default="A")
    p.add_argument("--b", required=True); p.add_argument("--b_name", default="B")
    p.add_argument("--pack", required=True)
    p.add_argument("--model", default="Qwen/Qwen2.5-VL-7B-Instruct")
    p.add_argument("--n", type=int, default=300)
    p.add_argument("--max_rel", type=int, default=20,
                   help="cap on relations per graph; a budget, NOT a target — either "
                        "model may emit fewer if its own confidence falls off")
    p.add_argument("--rel_frac", type=float, default=0.7,
                   help="keep pairs scoring >= rel_frac x the image's best pair. "
                        "Per-image relative, so it does not equalise graph lengths "
                        "across models the way a fixed K would")
    p.add_argument("--control_frac", type=float, default=0.15,
                   help="share of comparisons spent on the scramble control")
    p.add_argument("--pad_frac", type=float, default=0.15,
                   help="share of comparisons spent on the length-bias control")
    p.add_argument("--pad_extra", type=int, default=4,
                   help="fabricated relations appended in the length-bias control")
    p.add_argument("--controls_only", action="store_true",
                   help="spend the whole budget certifying the JUDGE: keep only images "
                        "where the scramble control is feasible, and run no head-to-head. "
                        "For topping up a control sample that was too thin to certify — "
                        "the sample size MUST be fixed in advance and the pooled result "
                        "reported whichever way it falls, or this is optional stopping.")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--votes", type=int, default=3,
                   help="sampled verdicts per presentation order (self-consistency). "
                        "1 = greedy, which measured a 70%% first-position bias")
    p.add_argument("--temperature", type=float, default=0.7)
    p.add_argument("--majority", type=float, default=0.67,
                   help="share of pooled votes a winner must hold; below it, TIE")
    p.add_argument("--max_new", type=int, default=300)
    p.add_argument("--out", required=True)
    a = p.parse_args()

    if "gemma" in a.model.lower():
        raise SystemExit(
            "refusing: our megasg supervision was generated by gemma-4-26B, so a Gemma "
            "judge measures self-preference. Use a different model family.")

    A, B = load_npz(a.a), load_npz(a.b)
    pack = Path(a.pack)
    meta = json.loads((pack / "meta.json").read_text())
    cat_names = list(meta["categories"])
    file_names = json.loads((pack / "file_names.json").read_text())
    img_dir = Path(meta["img_dir"])

    rowA = {int(v): i for i, v in enumerate(A["image_index"])}
    rowB = {int(v): i for i, v in enumerate(B["image_index"])}
    common = sorted(set(rowA) & set(rowB))
    rng = random.Random(a.seed)
    rng.shuffle(common)

    # Every image where both models said SOMETHING. Length is free to differ — that is
    # the point; requiring an equal count would silently select for the images where
    # neither model had anything extra to contribute.
    chosen = []
    for row in common:
        ia, ib = rowA[row], rowB[row]
        # Both models were handed the SAME detector boxes, so the box sets must agree
        # exactly; if they do not, the numbers drawn on the image mean different things
        # to the two graphs and nothing downstream is comparable.
        pa, pb = A["box_ptr"], B["box_ptr"]
        xa = A["boxes"][int(pa[ia]):int(pa[ia + 1])]
        xb = B["boxes"][int(pb[ib]):int(pb[ib + 1])]
        assert xa.shape == xb.shape and np.allclose(xa, xb, atol=1e-3), (
            f"image row {row}: {a.a_name} has {xa.shape[0]} boxes, {a.b_name} has "
            f"{xb.shape[0]} — the two records do not share a box set")
        # One shared naming for both graphs, taken from the same record that labels the
        # boxes drawn on the image.
        lab = obj_labels(A, ia)
        ta = triplets(A, ia, a.max_rel, a.rel_frac, cat_names, labels=lab)
        tb = triplets(B, ib, a.max_rel, a.rel_frac, cat_names, labels=lab)
        if ta and tb:
            chosen.append((row, ta, tb))
        if len(chosen) >= a.n:
            break
    la = np.array([len(t[1]) for t in chosen], np.float32)
    lb = np.array([len(t[2]) for t in chosen], np.float32)
    print(f"{len(chosen)} comparable images   "
          f"{a.a_name}: {la.mean():.1f} rel/graph (median {np.median(la):.0f})   "
          f"{a.b_name}: {lb.mean():.1f} rel/graph (median {np.median(lb):.0f})")

    import torch
    from transformers import AutoProcessor, AutoModelForImageTextToText
    print(f"loading judge: {a.model}")
    proc = AutoProcessor.from_pretrained(a.model)
    judge = AutoModelForImageTextToText.from_pretrained(
        a.model, dtype=torch.bfloat16, device_map="auto").eval()

    def ask(im, left, right):
        """`--votes` sampled verdicts for one presentation order, generated in a single
        batched call. Sampling (not greedy) is the point: self-consistency needs
        independent draws, and a lone greedy decode is what let a shallow primacy
        heuristic dominate the first run of this axis."""
        msg = [{"role": "user", "content": [
            {"type": "image"},
            {"type": "text", "text": f"{RUBRIC}\n\nGRAPH A:\n{fmt(left)}\n\n"
                                     f"GRAPH B:\n{fmt(right)}"}]}]
        text = proc.apply_chat_template(msg, tokenize=False, add_generation_prompt=True)
        inp = proc(text=[text], images=[im], return_tensors="pt").to(judge.device)
        with torch.no_grad():
            gen = judge.generate(**inp, max_new_tokens=a.max_new,
                                 do_sample=a.votes > 1, temperature=a.temperature,
                                 top_p=0.9, num_return_sequences=a.votes)
        outs = proc.batch_decode(gen[:, inp["input_ids"].shape[1]:],
                                 skip_special_tokens=True)
        return [parse(o) for o in outs]

    # Assign the controls BEFORE judging, and only to images where the corruption is
    # actually possible. Sampling them at random instead would silently starve the
    # scramble control: a graph needs >=3 distinct predicates to be worth permuting, and
    # a predicate-uniform model supplies very few such graphs.
    # per-index RNG so the feasibility probe and the judged scramble are the same draw
    plan, feas = {}, [i for i, (_, ta, _) in enumerate(chosen)
                      if scramble(ta, random.Random(a.seed + i)) is not None]
    if a.controls_only:
        # Drop every image that cannot carry the control, so no generation is spent on
        # a head-to-head we are not going to read. Feasibility is seeded by POSITION,
        # so it must be recomputed after the list is reindexed.
        chosen = [c for i, c in enumerate(chosen) if i in set(feas)]
        feas = [i for i, (_, ta, _) in enumerate(chosen)
                if scramble(ta, random.Random(a.seed + i)) is not None]
        chosen = [chosen[i] for i in feas]
        feas = [i for i, (_, ta, _) in enumerate(chosen)
                if scramble(ta, random.Random(a.seed + i)) is not None]
        assert len(feas) == len(chosen), "scramble feasibility unstable under reindexing"
        print(f"controls-only: {len(chosen)} scramble-feasible images")
    want_s = int(round(a.control_frac * len(chosen)))
    rng.shuffle(feas)
    for i in feas[:want_s]:
        plan[i] = "scramble"
    rest = [i for i in range(len(chosen)) if i not in plan]
    rng.shuffle(rest)
    for i in rest[:int(round(a.pad_frac * len(chosen)))]:
        plan[i] = "pad"
    print(f"controls: scramble {sum(v=='scramble' for v in plan.values())} "
          f"(of {len(feas)} feasible), pad {sum(v=='pad' for v in plan.values())}, "
          f"head-to-head {len(chosen) - len(plan)}")
    if want_s and len(feas) < want_s:
        print(f"!! only {len(feas)} graphs have enough predicate diversity to scramble; "
              f"the floor test rests on a small sample — treat control_accuracy as noisy")

    records = []
    for n, (row, ta, tb) in enumerate(chosen):
        ia, ib = rowA[row], rowB[row]
        bA, bB = int(A["box_ptr"][ia]), int(A["box_ptr"][ia + 1])
        im = render(img_dir / file_names[row], A["boxes"][bA:bB],
                    obj_labels(A, ia), cat_names)

        # Both controls pit a model against a corrupted copy of ITSELF, so any consistent
        # preference is a property of the judge rather than of the systems compared.
        kind = plan.get(n, "head")
        if kind == "scramble":                    # same length, content destroyed
            left, right, truth = ta, scramble(ta, random.Random(a.seed + n)), "A"
        elif kind == "pad":                       # longer, partly false
            padded = pad(ta, rng, a.pad_extra)
            if len(padded) == len(ta):            # nothing could be fabricated
                kind, left, right, truth = "head", ta, tb, None
            else:
                left, right, truth = ta, padded, "A"
        else:
            left, right, truth = ta, tb, None

        fwd = ask(im, left, right)
        rev = ask(im, right, left)                   # swapped presentation
        SWAP = {"A": "B", "B": "A", "TIE": "TIE"}
        # Pool every vote in the ORIGINAL frame. Pooling across both orders beats
        # requiring the two orders to agree: it uses all the evidence, and a pure
        # position heuristic cancels instead of merely being discarded as a tie.
        votes = [v for v, _ in fwd if v] + [SWAP[v] for v, _ in rev if v]
        n_first = sum(v == "A" for v, _ in fwd if v) + sum(v == "A" for v, _ in rev if v)
        tally = collections.Counter(votes)
        verdict, agree = "TIE", False
        if votes:
            top, cnt = tally.most_common(1)[0]
            # supermajority, so a 4-2 split is not read as a preference
            if cnt >= a.majority * len(votes) and top != "TIE":
                verdict, agree = top, True
        r1 = next((r for v, r in fwd if v), "")

        records.append(dict(row=row, kind=kind, votes=votes, n_first_position=n_first,
                            agree=agree, verdict=verdict, reason=r1,
                            n_a=len(left), n_b=len(right),
                            a=[list(t) for t in left], b=[list(t) for t in right]))
        if (n + 1) % 20 == 0:
            print(f"  {n+1}/{len(chosen)}", flush=True)

    def rate(rs, want="A"):
        w = sum(r["verdict"] == want for r in rs)
        l = sum(r["verdict"] not in (want, "TIE") for r in rs)
        return w / max(1, w + l), w, l, len(rs) - w - l

    head = [r for r in records if r["kind"] == "head"]
    scr = [r for r in records if r["kind"] == "scramble"]
    pd_ = [r for r in records if r["kind"] == "pad"]

    wa = sum(r["verdict"] == "A" for r in head)
    wb = sum(r["verdict"] == "B" for r in head)
    tie = len(head) - wa - wb
    undecided = sum(not r["agree"] for r in records) / max(1, len(records))
    # Direct measurement of the failure that invalidated the greedy run: the share of
    # individual votes going to whichever graph was shown FIRST. 0.5 = no position
    # effect; the greedy single-vote judge measured ~0.70.
    tot_votes = sum(len(r["votes"]) for r in records)
    primacy = (sum(r["n_first_position"] for r in records) / tot_votes
               if tot_votes else float("nan"))
    ctrl, *_ = rate(scr)
    padr, *_ = rate(pd_)          # share preferring the SHORTER, truer graph

    # Coverage is a virtue, so it must not be conflated with the judge's taste for long
    # lists. Split the head-to-head by which graph was actually longer: if A only ever
    # wins when it is longer, the win is length. If it wins in both strata, it is not.
    def stratum(f):
        s = [r for r in head if f(r)]
        r_, w, l, t = rate(s)
        return {"n": len(s), "win_rate_a": r_ if w + l else None,
                "wins_a": w, "wins_b": l, "ties": t}

    n_a = np.array([r["n_a"] for r in head], np.float32) if head else np.zeros(1)
    n_b = np.array([r["n_b"] for r in head], np.float32) if head else np.zeros(1)

    summary = {
        "a_name": a.a_name, "b_name": a.b_name, "model": a.model,
        "max_rel": a.max_rel, "rel_frac": a.rel_frac,
        "n_compared": len(head), "wins_a": wa, "wins_b": wb, "ties": tie,
        "win_rate_a": wa / max(1, wa + wb), "decisive": wa + wb,
        "mean_rel_a": float(n_a.mean()), "mean_rel_b": float(n_b.mean()),
        "longer_a": int((n_a > n_b).sum()), "longer_b": int((n_b > n_a).sum()),
        "by_length": {"a_longer": stratum(lambda r: r["n_a"] > r["n_b"]),
                      "b_longer": stratum(lambda r: r["n_b"] > r["n_a"]),
                      "equal": stratum(lambda r: r["n_a"] == r["n_b"])},
        "votes_per_comparison": 2 * a.votes, "majority": a.majority,
        "undecided_rate": undecided, "primacy_rate": primacy,
        # decisive counts, so a control accuracy is never read without its sample size
        "control_n": len(scr), "control_decisive": sum(r["agree"] for r in scr),
        "control_accuracy": ctrl,
        "padding_n": len(pd_), "padding_decisive": sum(r["agree"] for r in pd_),
        "padding_resistance": padr,
        # Pre-registered gate. primacy <= 0.60 replaces the old flip-rate test: with
        # pooled voting a position effect biases the verdict rather than merely
        # destabilising it, so it must be bounded directly.
        "valid": (ctrl >= 0.75 and primacy <= 0.60
                  and sum(r["agree"] for r in scr) >= 10),
    }
    print("\n=== A5 LLM oracle ===")
    for k, v in summary.items():
        print(f"  {k}: {json.dumps(v) if isinstance(v, dict) else v}")
    if not summary["valid"]:
        print("\n!! CONTROLS FAILED — the judge cannot reliably tell an intact graph "
              "from a scrambled one, or it prefers whichever graph is shown first. The "
              "head-to-head numbers above are NOT interpretable.")
    # `rate([])` is 0.0 by construction, so an arm run with --pad_frac 0 would otherwise
    # report a spurious total length bias.
    if pd_ and padr < 0.5:
        print(f"\n!! LENGTH BIAS — the judge preferred a padded graph over its own "
              f"truthful shorter version {100*(1-padr):.0f}% of the time. Coverage wins "
              f"are inflated for whichever model is longer; read `by_length`, where the "
              f"stratum in which the winner was SHORTER is the trustworthy one.")

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps({"summary": summary, "records": records},
                                      indent=2))
    print("wrote", a.out)


