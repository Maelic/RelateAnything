"""A5 — LLM-as-oracle: whole-graph quality, no ground truth.

WHY THIS AXIS EXISTS
--------------------
A1-A4 all score a prediction against annotations, so they inherit those annotations'
blind spots: a relation that is true but unlabelled counts as a false positive, and a
graph is only ever as good as the corpus it is compared to. This axis asks a different
question — *is this a good scene graph?* — with **no ground truth in the prompt at all**.
It is the closest we get to a downstream-task evaluation without committing to one
downstream task.

Crucially the judge sees the WHOLE graph, never a relation at a time: global coherence
(does this read as one consistent scene, does it capture what matters) is exactly what
per-triplet matching cannot measure.

CONTROLS — this is what separates an oracle from vibes
------------------------------------------------------
1. **The judge must not be Gemma.** Our megasg supervision was generated by
   gemma-4-26B-A4B-it, so a Gemma judge would show self-preference for our own model's
   output distribution. Default is Qwen2.5-VL (different family, different pretraining).
2. **Position bias**: every pair is judged in BOTH orders AND `--votes` times per
   order under sampling; all votes are pooled in one frame and a winner needs a
   supermajority. Pooling beats requiring the two orders to agree, because a pure
   position heuristic then cancels instead of merely being discarded. `primacy_rate`
   reports the share of votes going to whichever graph was shown first: 0.5 is
   unbiased, and a single greedy decode measured 0.70 on this task, which is what
   invalidated the first run of this axis.
3. **Length is MEASURED, not suppressed.** Comprehensiveness is a real virtue in SGG: a
   model that correctly describes more of the scene is a better model, and forcing both
   graphs to the same K would define that advantage out of existence. So each model
   emits the graph it would actually deploy — every pair scoring within `--rel_frac` of
   that image's best pair, capped at `--max_rel`. The relative rule matters: the two
   models' scores live on different scales, so an absolute threshold would measure
   calibration, while a per-image relative one lets each model's own confidence spread
   decide how much it says. What remains is the judge's own preference for longer text,
   and that is measured directly by the padding control below rather than assumed away.
4. **Padding control**: a fraction of comparisons pit a graph against ITSELF PLUS
   fabricated relations — same objects, same vocabulary, strictly longer, strictly less
   true. A judge that prefers the padded graph is rewarding length rather than content;
   `padding_resistance` quantifies exactly how much, and the head-to-head is reported
   stratified by which graph was longer so a reader can see the effect directly.
5. **Degenerate control**: a fraction of comparisons pit a model against a SCRAMBLED
   version of its own graph (predicates permuted across pairs, length preserved). A
   judge that cannot reliably prefer the intact graph is not measuring anything, and the
   head-to-head numbers must be discarded. Floor test, reported as `control_accuracy`.
6. **Vocabulary-breadth confound**: our model can emit ~10k predicate strings, OvSGTR
   at most ~150 (its prompt is capped at max_text_len=512). Run BOTH arms — `--vocab
   pack` restricts us to the benchmark's predicates, `--vocab train` deploys the full
   one — so a win can be attributed to relation choice rather than richer wording.

    python benchmark/llm_judge.py \
        --a runs/judge/relsgg_psg_test_yoloworld.npz --a_name RelSGG \
        --b runs/ovsgtr/... --b_name OvSGTR \
        --pack runs/packed/psg/test --n 300 --topk 10 --out runs/judge/verdicts.json
"""
